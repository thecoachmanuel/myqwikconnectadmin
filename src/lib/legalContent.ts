/** Legacy markers that indicate content still branded for the old template. */
export const LEGACY_BRAND_MARKERS = [
  'Orange Dating',
  'orangeapp.com',
  'Orange app',
  'About Orange',
  'myqwikconnect.com',
];

/** Returns true when the given stored page content still carries old branding. */
export function isLegacyBrandContent(content: unknown): boolean {
  if (typeof content !== 'string' || content.trim() === '') return true;
  return LEGACY_BRAND_MARKERS.some((marker) => content.includes(marker));
}
